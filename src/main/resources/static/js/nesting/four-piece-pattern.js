export function fourPieceParts(sizeCounts = {'130':2, '140':2}) {
    return OUTLINES.map(({size, name, points}, index) => {
        const minLength = Math.min(...points.map(([length]) => length));
        const maxWidth = Math.max(...points.map(([, width]) => width));
        // A quarter turn maps the report's rightward grain to the solver's +y
        // roll direction while preserving each sleeve's handedness.
        const shape = polygon(points.map(([length, width]) => ({
            x:Math.round((maxWidth - width) * MM_PER_WIDTH_PIXEL),
            y:Math.round((length - minLength) * MM_PER_LENGTH_PIXEL)
        })));
        return {id:index + 1, name:`${size}码 · ${name}`, quantity:sizeCounts[size], shape, allowRotation:false};
    }).filter(part => part.quantity > 0);
}
